const CONFIDENCE_LABELS = {
  documented: '有据',
  inferred: '推断',
  speculative: '猜测',
  absent: '未记录',
};

function dim(level, summary, confidence = 'documented', note) {
  const d = { level, summary, confidence };
  if (note) d.note = note;
  return d;
}

function snap(year, eraLabel, opts) {
  return {
    year,
    eraLabel,
    eraTemplate: opts.eraTemplate,
    evidenceTypes: opts.evidenceTypes || ['literature', 'archaeology'],
    worldContext: opts.worldContext,
    evidenceNote: opts.evidenceNote,
    sources: opts.sources,
    dimensions: opts.dimensions,
    dynasty: opts.dynasty,
    group: opts.group,
    periodId: opts.periodId,
    ...(opts.controversies ? { controversies: opts.controversies } : {}),
  };
}

function buildCiv({ id, country, color, snapshots }) {
  return {
    meta: {
      title: `${country}历史 · 十维探索`,
      subtitle: '科学方法驱动的定性历史重建',
      country,
      countryId: id,
      color,
    },
    dimensions: DIMENSIONS,
    confidenceLabels: CONFIDENCE_LABELS,
    snapshots,
  };
}

